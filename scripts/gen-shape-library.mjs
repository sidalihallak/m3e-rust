#!/usr/bin/env node
// Run with Node24+ --experimental-strip-types and a local copy of the pinned
// shadcn-m3e packages/m3e/src/lib/shape-library.ts (MIT; shapes © Google LLC).
// Example: node --experimental-strip-types scripts/gen-shape-library.mjs /tmp/shape-library.mts
import {writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
const source=process.argv[2];
if(!source)throw new Error('Supply the inspected upstream shape-library.mts');
const {SHAPE_NAMES,shapeClipPath}=await import(pathToFileURL(resolve(source)).href);
const numeric={'4':'Four','6':'Six','7':'Seven','8':'Eight','9':'Nine','12':'Twelve'};
const variants=SHAPE_NAMES.map(name=>name.split('-').map(word=>numeric[word]??word[0].toUpperCase()+word.slice(1)).join(''));
const clips=SHAPE_NAMES.map(shapeClipPath);
if(SHAPE_NAMES.length!==35||clips.some(clip=>clip.split(',').length!==300))throw new Error('Unexpected upstream shape count or sample count');
const lines=[
 '// Generated by scripts/gen-shape-library.mjs. Do not edit by hand.',
 '// Source: shadcn-m3e c37c0d2 shape-library.ts (MIT), @m3e/shape (MIT); shape data © Google LLC.',
 '// Same300 samples, winding/phase alignment and two-decimal percentages as upstream.',
 '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]','pub enum ShapeName {',...variants.map(v=>`    ${v},`),'}',
 'impl ShapeName {','    pub const ALL: [Self;35] = [',...variants.map(v=>`        Self::${v},`),'    ];',
 '    pub const fn name(self) -> &\'static str {','        match self {',...variants.map((v,i)=>`            Self::${v} => ${JSON.stringify(SHAPE_NAMES[i])},`),'        }','    }',
 '    pub const fn clip_path(self) -> &\'static str {','        match self {',...variants.map((v,i)=>`            Self::${v} => ${JSON.stringify(clips[i])},`),'        }','    }','}',
];
writeFileSync(new URL('../src/shape_library.rs',import.meta.url),lines.join('\n')+'\n');
console.log('Generated35 exact upstream clip paths,300 points each.');
