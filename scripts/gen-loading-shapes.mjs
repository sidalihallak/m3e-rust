#!/usr/bin/env node
// Generates src/loading_shapes.rs: the seven loading-indicator shapes as 180-point
// polygons, normalised to a radius of 1.
//
// Source: upstream lib/shapes.ts (shadcn-m3e, MIT; SVG shape data from the
// official Material Design shape assets). Export the resampled shapes first:
//
//   cp <shadcn-m3e>/packages/m3e/src/lib/shapes.ts shapes-src.mts
//   echo 'import {getShapes,SHAPE_COUNT} from "./shapes-src.mts";
//     console.log(JSON.stringify({count:SHAPE_COUNT,points:getShapes()[0].length,shapes:getShapes().map(s=>s.map(([x,y])=>[+x.toFixed(4),+y.toFixed(4)]))}))' > dump.mts
//   node --experimental-strip-types dump.mts > loading-shapes.json
//   node scripts/gen-loading-shapes.mjs loading-shapes.json
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const input = process.argv[2];
if (!input) {
  console.error("usage: node scripts/gen-loading-shapes.mjs <loading-shapes.json>");
  process.exit(1);
}
const data = JSON.parse(readFileSync(input, "utf8"));
const lines = [];
lines.push("// Generated by scripts/gen-loading-shapes.mjs. Do not edit by hand.");
lines.push("// Seven loading-indicator shapes, 180 points each, normalised to radius 1.");
lines.push("// Source: shadcn-m3e lib/shapes.ts (MIT); official Material Design shape data.");
lines.push("");
lines.push(`pub const SHAPE_COUNT: usize = ${data.count};`);
lines.push(`pub const POINTS_PER_SHAPE: usize = ${data.points};`);
lines.push("");
lines.push(`pub const SHAPES: [[[f32; 2]; ${data.points}]; ${data.count}] = [`);
for (const shape of data.shapes) {
  lines.push("    [");
  for (const [x, y] of shape) lines.push(`        [${Number(x).toFixed(4)}, ${Number(y).toFixed(4)}],`);
  lines.push("    ],");
}
lines.push("];");
const target = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "loading_shapes.rs");
writeFileSync(target, lines.join("\n") + "\n");
console.log(`wrote ${data.count} shapes to ${target}`);
